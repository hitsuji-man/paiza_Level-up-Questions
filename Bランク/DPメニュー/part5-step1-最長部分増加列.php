<?php
    $n = (int) trim(fgets(STDIN));
    for ($i = 1; $i <= $n; $i++) { 
        $a[$i] = (int) trim(fgets(STDIN));
    }

    $dp[1] = 1;
    // $dp[$i]: 木 i を最後に残す場合、最大で何本の木を残せるか
    for ($i = 2; $i <= $n; $i++) {
        // 外側のループ: 最後にする木 i を選ぶ 
        $dp[$i] = 1;    // 木 i のみからなる部分列の長さ
        for ($j = 1; $j <= $i - 1; $j++) { 
            // 内側のループ: 木 i より左にある木を1本ずつ調べる
            if ($a[$j] < $a[$i]) {  // 木 j の後ろに木 i を繋げても高さが増加するか
                // 最後が木 j であるような増加部分列の末尾に木 i をくっつける
                /**
                 * 2つの大きい方を比較
                 * $dp[$i]: これまで見つけた、木 i で終わる最大本数
                 * $dp[$j] + 1: 今回木 j の後ろに繋いで作った本数
                 */
                $dp[$i] = max($dp[$i], $dp[$j] + 1);
            }
        }
    }

    $max = max($dp);
    echo $max . "\n";