<?php
    $n = (int) trim(fgets(STDIN));

    $dp[0] = 1;
    for ($i = 1; $i <= $n; $i++) { 
        $dp[$i] = 0;    // 数える前に合計を0にする処理
        if ($i >= 1) {
        // 1. 右側の $dp[$i] に入っている値を取り出す。
        // 2. $dp[$i - 1] の値を足す。
        // 3. 計算結果を、左側の $dp[$i] に入れる。
        // 計算する前に、右側の$dp[$i]に値が入っている必要がある。そのため、先に0を入れる
            $dp[$i] = $dp[$i] + $dp[$i - 1];    // 1段下から、1段登って到着する方法
        } 
        if ($i >= 2) {
            $dp[$i] = $dp[$i] + $dp[$i - 2];    // 2段下から、2段登って到着する方法
        }
        /**
         * 今数えているのが 5段目(i = 5)なら
         * $dp[4]: 4段目まで来た各方法に、1段登る動きを付け足す
         * $dp[3]: 4段目まで来た各方法に、2段登る動きを付け足す
         * 1 や 2 は登る段数、$dp[...]の値は方法の数
         */
    }

    echo $dp[$n] . "\n";