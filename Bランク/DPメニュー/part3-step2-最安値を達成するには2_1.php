<?php
    // りんご2個がa円で、りんご5個がb円で売られている
    [$n, $a, $b] = array_map('intval', explode(" ", trim(fgets(STDIN))));

    // 余分に買う場合も考えて、n + 4 個まで計算する
    $limit = $n + 4;
    // dp[i]は「ちょうど i 個買うための最小金額」とし、最初は全て購入不可能にする
    $dp = array_fill(0, $limit + 1, PHP_INT_MAX);
    // 0個なら何も買わないため、必要な金額は0円
    $dp[0] = 0;

    // dp[$i]: ちょうど i 個買うための最小金額
    for ($i = 1; $i <= $limit; $i++) { 
        // i - 2 が負にならず、ちょうど i -2 個買える場合に、2個セットの追加を検討する
        if ($i >= 2 && $dp[$i - 2] !== PHP_INT_MAX) {
            // 現在の最小金額と、i - 2個の最小金額に2個セットを足した金額を比較する
            $dp[$i] = min($dp[$i], $dp[$i - 2] + $a);
        }

        // i - 5 が負にならず、ちょうど i -5 個買える場合に、5個セットの追加を検討する
        if ($i >= 5 && $dp[$i - 5] !== PHP_INT_MAX) {
            // 現在の最小金額と、i - 5個の最小金額に5個セットを足した金額を比較する
            $dp[$i] = min($dp[$i], $dp[$i - 5] + $b);
        }
    }

    // 答えの初期値を、実際の購入金額より十分大きな値にする
    $answer = PHP_INT_MAX;
    // n 個以上買う場合の最小金額
    for ($i = $n; $i <= $limit; $i++) { 
        // これまでの答えと、ちょうど i 個買う最小金額のうち、安い方を答えにする
        $answer = min($answer, $dp[$i]);
    }

    echo $answer . "\n";